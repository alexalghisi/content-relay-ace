"""Turns the HeyGen demo lessons (teacher + pupil, real lip-sync, both voiced in HeyGen) into web videos.

Run: python3 scripts/proceseaza-video-demo.py <folder with <cheie>.mp4 exported from HeyGen>   (needs bun, ffmpeg)
Writes public/demo-video/lectii/<cheie>.mp4 + .jpg and src/components/profesor-ai/demo-video-lectii.generated.ts.
Every HeyGen scene is one line of the lesson, so the cuts between scenes give the caption timings.
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "public", "demo-video", "lectii")
GEN = os.path.join(ROOT, "src", "components", "profesor-ai", "demo-video-lectii.generated.ts")


def durata(f):
    return float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f]).strip())


def taieturi(f, prag):
    log = subprocess.run(["ffmpeg", "-i", f, "-vf", f"select='gt(scene,{prag})',showinfo", "-an", "-f", "null", "-"],
                         capture_output=True, text=True).stderr
    return [float(x) for x in re.findall(r"pts_time:([0-9.]+)", log)]


def main():
    src = sys.argv[1]
    os.makedirs(OUT, exist_ok=True)
    dump = os.path.join(ROOT, ".cache-video-demo.ts")
    open(dump, "w").write('import { LECTII, cheieLectie } from "./src/components/profesor-ai/demo-repertoriu";\n'
                          'console.log(JSON.stringify(LECTII.map((l) => ({ k: cheieLectie(l), n: l.replici.length }))));\n')
    lectii = json.loads(subprocess.check_output(["bun", dump], cwd=ROOT))
    os.remove(dump)
    gen = {}
    if os.path.exists(GEN):
        gen = json.loads(re.search(r"= (\{.*\});", open(GEN).read(), re.S).group(1))
    for l in lectii:
        f = os.path.join(src, l["k"] + ".mp4")
        if not os.path.exists(f):
            continue
        d = durata(f)
        cut = []
        for prag in (0.15, 0.1, 0.25, 0.3):
            cut = taieturi(f, prag)
            if len(cut) == l["n"] - 1:
                break
        if len(cut) != l["n"] - 1:
            print(f"!! {l['k']}: {len(cut) + 1} scene, aștept {l['n']}"); continue
        margini = [0.0] + cut + [d]
        replici = [[round(margini[i], 2), round(margini[i + 1], 2)] for i in range(l["n"])]
        dest = os.path.join(OUT, l["k"] + ".mp4")
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", f, "-vf", "scale=854:480", "-c:v", "libx264", "-preset", "slow",
                        "-crf", "29", "-profile:v", "main", "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "64k", "-ac", "1",
                        "-movflags", "+faststart", dest], check=True)
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-ss", "0.5", "-i", dest, "-frames:v", "1", "-q:v", "5",
                        os.path.join(OUT, l["k"] + ".jpg")], check=True)
        gen[l["k"]] = {"durata": round(d, 2), "replici": replici}
        print(f"ok {l['k']}: {d:.1f}s, {l['n']} replici")
    with open(GEN, "w") as o:
        o.write("// Generated by scripts/proceseaza-video-demo.py — do not edit by hand.\n"
                "// [start, end] in seconds of each lesson line in public/demo-video/lectii/<cheie>.mp4 (one HeyGen scene per line).\n"
                "export const VIDEO_DEMO: Record<string, { durata: number; replici: [number, number][] }> = "
                + json.dumps(dict(sorted(gen.items())), indent=1) + ";\n")


if __name__ == "__main__":
    main()
